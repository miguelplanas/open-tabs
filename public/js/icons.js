const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

// Throws on an unknown name: a typo should fail loudly in a test, not render
// an empty button on the phone.
export function icon(name, { label, cls } = {}) {
  const body = ICONS[name];
  if (!body) throw new Error(`Unknown icon: ${name}`);
  const klass = cls ? `i ${esc(cls)}` : 'i';
  const a11y = label ? `role="img" aria-label="${esc(label)}"` : 'aria-hidden="true"';
  return `<svg class="${klass}" viewBox="0 0 24 24" ${a11y} focusable="false">${body}</svg>`;
}

